"""Check for Part 23's separately accepted cache bundles without running models.

Usage: python tools/check_part23_qa_inputs.py [CACHE_DIR]
Default CACHE_DIR is this checkout's .cache/ai23. Presence is not proof of
scientific acceptance or a guarantee that companion data is complete.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = {
    'lms_qa_original_schedule': 'bits/character results',
    'patches_qa_corrected_boundary': 'byte-boundary analysis',
    'omni_budget_qa_accepted': 'Omni measured budget',
    'bpe_qa_accepted': 'outro text recap',
    'recap_modalities_qa_accepted': 'outro modality recap',
}


def missing_inputs(cache_dir: Path) -> list[str]:
    return [name for name in REQUIRED if not (cache_dir / f'{name}.json').is_file()]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache_dir', nargs='?', type=Path, default=ROOT / '.cache' / 'ai23')
    args = parser.parse_args(argv)
    missing = missing_inputs(args.cache_dir)
    for name in REQUIRED:
        print(f"{'MISSING' if name in missing else 'PRESENT'}  {name}.json  ({REQUIRED[name]})")
    print('Presence alone does not verify acceptance or companion files.')
    if missing:
        print('Missing bundles are not automatically generated by the standard Part 23 compute registry.')
    return 1 if missing else 0


if __name__ == '__main__':
    raise SystemExit(main())
