    def definition(self):
        rows = [
            cmath(r"E[X \mid \mathcal G]", r":", r"\text{a } \mathcal G\text{-measurable } Y \text{ with } \textstyle\int_A Y \, dP = \int_A X \, dP \ \ \forall A \in \mathcal G", font_size=30),
            cmath(r"\text{exists}", r":", r"\nu(A) = \textstyle\int_A X\, dP \ll P|_{\mathcal G} \ \Rightarrow \ Y = d\nu / dP|_{\mathcal G}", font_size=32),
            cmath(r"\text{unique}", r":", r"\text{up to a } P\text{-null set}", font_size=32),
            cmath(r"\mathcal G = \sigma(B)", r":", r"E[X \mid \mathcal G] = E[X \mid B]\, 1_B + E[X \mid B^c]\, 1_{B^c}", font_size=32),
        ]
        rows[0][-1].set_color(MARTC)
        whys = [why(r"Kolmogorov (1933)"), why(r"Radon--Nikodym"), why(r"a random variable, \ not a number"), why(r"the elementary case")]
        with self.voiceover(
            "<bookmark mark='a'/> Kolmogorov's definition: the conditional expectation of X given the information G is a "
            "random variable that depends only on that information, and that has the same integral as X over every event in "
            "G. <bookmark mark='b'/> It exists by the Radon–Nikodym theorem: integrating X over the events of G defines a "
            "measure that vanishes wherever P does, and its density with respect to P restricted to G is the conditional "
            "expectation. <bookmark mark='c'/> It is unique up to a null set, and it is a random variable, not a number. "
            "<bookmark mark='d'/> When G is generated by a single event B, it takes two values, the elementary averages "
            "over B and over its complement, and the old definition is recovered."
        ) as vo:
            step = ladder(self, rows, whys, keep=4, top=2.6, x=-0.9, buff=0.85, edge=6.9)
            for k, m_ in enumerate("abcd"):
                vo.wait_until(m_)
                step(k, transform=False)
        self.clear_scene()

