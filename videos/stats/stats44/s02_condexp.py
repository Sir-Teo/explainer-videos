    def variance(self):
        rows = [
            cmath(r"\text{Var}\, X", r"=", r"E\big[\text{Var}(X \mid \mathcal G)\big] + \text{Var}\big(E[X \mid \mathcal G]\big)", font_size=34),
            cmath(r"\text{proof}", r":", r"\text{Pythagoras: \ } X - EX = (X - E[X \mid \mathcal G]) + (E[X \mid \mathcal G] - EX), \ \perp", font_size=28),
            cmath(r"\text{Rao--Blackwell}", r":", r"\text{conditioning never increases variance}", font_size=32),
            cmath(r"\text{seen in}", r":", r"\text{Rubin's rules (Part 41), \ random effects (Part 25), \ Part 45's estimators}", font_size=28),
        ]
        rows[0][-1].set_color(MARTC)
        whys = [why(r"total variance"), why(r"the projection picture"), why(r"Part 45"), why(r"one identity, \ three uses")]
        with self.voiceover(
            "<bookmark mark='a'/> The projection picture gives the law of total variance at once: the variance of X is the "
            "expected conditional variance plus the variance of the conditional expectation. <bookmark mark='b'/> It is "
            "Pythagoras: X minus its mean splits into two orthogonal pieces, the error of the projection and the projection's "
            "own deviation. <bookmark mark='c'/> So replacing an estimator by its conditional expectation given a statistic "
            "never increases its variance, which is the Rao–Blackwell theorem of the next part. <bookmark mark='d'/> The same "
            "identity gave Rubin's rules in Part forty-one and the split of variance between and within groups in Part "
            "twenty-five."
        ) as vo:
            step = ladder(self, rows, whys, keep=4, top=2.6, x=-0.9, buff=0.85, edge=6.9)
            for k, m_ in enumerate("abcd"):
                vo.wait_until(m_)
                step(k, transform=False)
        self.clear_scene()
