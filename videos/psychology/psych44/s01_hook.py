from __future__ import annotations

from videos.psychology.psych44.common import *  # noqa: F403
from videos.psychology.psych44.diagrams import three


class Hook(VoiceoverScene):
    def construct(self):
        self.diagrams()
        self.wright()
        self.question()
        self.objectives()

    def diagrams(self):
        d = load("equivalent")
        head = heading(r"One matrix, \ three diagrams")
        R = d["R"]
        mat = VGroup(*[label(f"{R[i, j]:.2f}", font_size=34, color=WHITE if i != j else GREY_B)
                       for i in range(3) for j in range(3)]).arrange_in_grid(3, 3, buff=(0.6, 0.4))
        names = VGroup(*[label(t, font_size=28, color=GREY_A) for t in "XMY"])
        for i, nm in enumerate(names):
            nm.next_to(mat[3 * i], LEFT, buff=0.3)
        tbl = VGroup(mat, names).move_to([-4.0, 0.7, 0])
        diags = VGroup()
        for kind, c in (("chain", GOOD), ("reverse", SYMP), ("fork", MODEL)):
            dg = three(kind, c).scale(0.75)
            chi = label(rf"$\chi^2 = {d[kind]:.2f}$, \ 1 df", font_size=20, color=c).next_to(dg, RIGHT, buff=0.3)
            diags.add(VGroup(dg, chi))
        diags.arrange(DOWN, aligned_edge=LEFT, buff=0.4).move_to([2.7, 0.8, 0])
        rows = rows_of([
            (r"1{,}000 simulated people, \ generated by a chain: \ X causes M, \ and M causes Y", WHITE),
            (r"the chain, \ the chain reversed, \ and a fork with M as common cause fit these data exactly equally well",
             MODEL),
            (r"the data cannot say which is true; \ only the design can", YOU),
        ], 12.4, 21, 0.3).move_to([0, -2.4, 0])
        with self.voiceover(
            "Here is a correlation matrix for three variables. <bookmark mark='a'/> A thousand simulated people, "
            "generated by a chain: X causes M, and M causes Y. <bookmark mark='b'/> Now fit three diagrams: the "
            "chain, the chain reversed, and a fork, with M as the common cause of both. They fit these data exactly "
            "equally well, to the second decimal place. <bookmark mark='c'/> The data can't say which diagram is "
            "true. Only the design of the study can."
        ) as vo:
            self.play(FadeIn(head), FadeIn(tbl))
            vo.wait_until("a")
            self.play(FadeIn(rows[0]))
            vo.wait_until("b")
            self.play(FadeIn(rows[1]), LaggedStart(*[FadeIn(x) for x in diags], lag_ratio=0.4), run_time=2.5)
            vo.wait_until("c")
            self.play(FadeIn(rows[2]))
        self.clear_scene()

    def wright(self):
        head = heading(r"Arrows, \ then factors")
        steps = VGroup()
        for yr, txt, c in (
                (r"1921", r"Wright, \ a geneticist, \ draws arrows between variables and shows how their correlations "
                          r"follow from the arrows: \ path analysis", GOOD),
                (r"1904", r"Spearman had already explained correlations by an unseen common factor (Part 32)", SYMP),
                (r"1969", r"Jöreskog joins the two: \ factors measured by indicators, \ and arrows between the "
                          r"factors, \ estimated by maximum likelihood", MODEL),
                (r"since", r"the structural equation model becomes psychology's way to state a theory about "
                           r"unobservables; \ its standard abuse is to forget the diagrams that fit equally", YOU)):
            steps.add(VGroup(word_chip(yr, color=c, font_size=20, width=1.6), wrapped_label(txt, 10.0, 20, WHITE))
                      .arrange(RIGHT, buff=0.35))
        steps.arrange(DOWN, aligned_edge=LEFT, buff=0.4).move_to([0, -0.3, 0])
        tag = historical_tag(r"Wright (1921); \ Jöreskog (1969)")
        with self.voiceover(
            "The idea has two roots. <bookmark mark='a'/> In 1921 the geneticist Sewall Wright drew arrows between "
            "variables, and showed how their correlations follow from the arrows. He called it path analysis. "
            "<bookmark mark='b'/> Spearman had already explained correlations by an unseen common factor, in Part "
            "32. <bookmark mark='c'/> In 1969 Karl Jöreskog joined the two: factors measured by indicators, arrows "
            "between the factors, all estimated by maximum likelihood. <bookmark mark='d'/> The structural equation "
            "model became psychology's standard way to state a theory about things it can't observe. Its standard "
            "abuse is to forget the diagrams that fit equally well."
        ) as vo:
            self.play(FadeIn(head), FadeIn(tag))
            for m, s in zip("abcd", steps):
                vo.wait_until(m)
                self.play(FadeIn(s, shift=RIGHT * 0.15))
        self.clear_scene()

    def question(self):
        head = heading(r"Today: \ how do you model what you cannot see?")
        rows = rows_of([
            (r"paths, \ factors, \ and the model that joins them", SYMP),
            (r"estimation, \ fit, \ and the cut-offs people use to judge it", MODEL),
            (r"invariance, \ mediation, \ and models that fit equally", PERSON),
            (r"time, \ networks, \ and how to read an SEM paper", GOOD),
        ], 12.4, 27, 0.48).move_to([0, -0.2, 0])
        with self.voiceover(
            "So this part asks how to model something you can't observe, and how to know the model isn't a fiction. "
            "<bookmark mark='a'/> Paths, factors, and the model that joins them. <bookmark mark='b'/> Estimation, "
            "fit, and the cut-offs people use to judge it. <bookmark mark='c'/> Invariance, mediation, and models "
            "that fit equally. <bookmark mark='d'/> And time, networks, and how to read a paper that uses all this."
        ) as vo:
            self.play(FadeIn(head))
            for m, r in zip("abcd", rows):
                vo.wait_until(m)
                self.play(FadeIn(r, shift=RIGHT * 0.15))
        self.clear_scene()

    def objectives(self):
        head = VGroup(label(r"Part 44", font_size=34, color=GREY_B), label(r"Latent Variables", font_size=56))
        head.arrange(DOWN, buff=0.25)
        obj = objectives_card([
            r"Wright's tracing rules, \ derived",
            r"the factor model, \ identification, \ and maximum likelihood",
            r"fit: \ the chi-square test, \ RMSEA, \ CFI and dynamic cut-offs",
            r"latent regression, \ and measurement invariance across groups",
            r"mediation, \ and why it stays correlational",
            r"equivalent models, \ growth over time, \ and factors against networks",
        ], color=P.ACCENT, font_size=31, width=13.2)
        with self.voiceover(
            "This is Part 44 of Psychology, Built: latent variables, and the start of the graduate toolkit. "
            "<bookmark mark='a'/> We'll derive Wright's tracing rules. We'll build the factor model, identify it, and "
            "estimate it by maximum likelihood. We'll judge fit: the chi-square test, RMSEA, CFI, and cut-offs that "
            "depend on the model. We'll correct a regression for unreliability, and test whether a measure means the "
            "same thing in two groups. We'll see why mediation stays correlational. And we'll meet equivalent models, "
            "growth over time, and factors against networks."
        ) as vo:
            self.play(FadeIn(head, shift=UP * 0.2))
            vo.wait_until("a")
            self.play(head.animate.scale(0.6).to_edge(UP, buff=0.3))
            obj.next_to(head, DOWN, buff=0.45)
            self.play(LaggedStart(*[FadeIn(r, shift=RIGHT * 0.2) for r in obj], lag_ratio=0.9), run_time=20.0)
        self.clear_scene()
