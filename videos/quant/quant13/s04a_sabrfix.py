    def pde_eq(self, p):
        rows = [cmath(r"\partial_T Q", r"=", r"\tfrac12\,\partial_F^2\big(D^2(F)\,E(T, F)\,Q\big),\qquad 0 < F < F_{\max}",
                      font_size=34, colors={r"\partial_T Q": RV}),
                cmath(r"D(F)", r"=", r"\sqrt{\alpha^2 + 2\alpha\rho\nu\,y + \nu^2 y^2}\ F^{\beta},\quad "
                      r"y = \frac{F^{1-\beta} - f^{1-\beta}}{1 - \beta}", font_size=32, colors={r"D(F)": RV}),
                cmath(r"E(T, F)", r"=", r"e^{\rho\nu\alpha\,\Gamma(F)\,T},\quad \Gamma(F) = \frac{F^\beta - f^\beta}{F - f}",
                      font_size=32, colors={r"E(T, F)": RV}),
                cmath(r"\frac{d}{dT}\Big(\int_0^{F_{\max}}\! Q\,dF + Q_L + Q_R\Big)", r"=", r"0", font_size=34,
                      colors={r"\frac{d}{dT}\Big(\int_0^{F_{\max}}\! Q\,dF + Q_L + Q_R\Big)": RV})]
        whys = [why(r"Hagan, Kumar, Lesniewski and Woodward (2014): integrate the volatility out of SABR's forward "
                    r"equation, to the same order as the 2002 formula, and keep the result as an equation for the density "
                    r"$Q$ of $F$ alone", 20),
                why(r"the effective local volatility of the forward: the 2002 expansion's ingredients", 20),
                why(r"a slowly varying time factor from the correlation", 20),
                why(r"absorbing boundaries: probability flowing out at $F = 0$ is kept as a mass $Q_L$ (and at $F_{\max}$ as "
                    r"$Q_R$), so the total is exactly 1; the density solved this way can never go negative", 20)]
        step = ladder(self, rows, whys, keep=4, top=2.9, x=-1.0, buff=0.6, edge=6.9)
        with self.voiceover(
            "In 2014 Hagan and the same co-authors published the repair, arbitrage-free SABR. The idea: do not "
            "differentiate an approximate price. Instead, integrate the volatility out of SABR's forward equation, to "
            "the same order of accuracy as the old formula, and keep what is left as an equation for the density of "
            "the forward itself. <bookmark mark='a'/> It is a one-dimensional diffusion equation, with an effective "
            "local volatility D built from the same ingredients as the 2002 expansion, <bookmark mark='b'/> and a "
            "slowly varying factor E from the correlation. <bookmark mark='c'/> At zero the boundary absorbs: "
            "probability that reaches zero stays there, as a mass, and the books balance exactly. A density solved "
            "from a diffusion equation cannot go negative. So the arbitrage is gone by construction."
        ) as vo:
            step(0)
            vo.wait_until("a")
            step(1)
            vo.wait_until("b")
            step(2)
            vo.wait_until("c")
            step(3)
        self.wait(0.4)
        self.clear_scene()

    def sheet(self, p):
        F = np.asarray(p["F"])
        sh = p["sheet"]
        Ts = np.array([z["T"] for z in sh])
        m = F <= 0.1
        F = F[m]
        Qs = np.array([np.asarray(z["Q"])[m] for z in sh])
        Hs = np.array([np.asarray(z["hagan"])[m] for z in sh])
        top = 70.0
        ax = ThreeDAxes(x_range=[0, 0.1, 0.02], y_range=[0, 10, 2], z_range=[-40, top, 20], x_length=6.6, y_length=5.6,
                        z_length=3.6, tips=False,
                        axis_config={"stroke_color": GREY_C, "include_ticks": False, "stroke_width": 2})
        ax.shift(DOWN * 0.4)

        def line(vals, T, col, sw=3):
            return VMobject(stroke_color=col, stroke_width=sw).set_points_as_corners(
                [ax.c2p(x, T, float(np.clip(z, -40, top))) for x, z in zip(F, vals)])

        pde = VGroup(*[line(q, T, RV) for q, T in zip(Qs, Ts)])
        hag = VGroup(*[line(h, T, BAD, 2.5) for h, T in zip(Hs, Ts)])
        zero = Polygon(ax.c2p(0, 0, 0), ax.c2p(0.1, 0, 0), ax.c2p(0.1, 10, 0), ax.c2p(0, 10, 0), stroke_width=0,
                       fill_color=GREY_D, fill_opacity=0.25)
        bars = VGroup(*[Line(ax.c2p(0, T, 0), ax.c2p(0, T, min(z["QL"] * 300, top)), color=VAR, stroke_width=8)
                        for z, T in zip(sh, Ts)])
        hint = VGroup(label(r"the density of a 3\% forward rate, over (rate 0 to 10\%, maturity 0 to 10 years)",
                            font_size=20, color=GREY_A),
                      legend([(RV, r"arbitrage-free SABR (the PDE)"), (BAD, r"Hagan's 2002 formula, differentiated twice"),
                              (VAR, r"mass absorbed at zero (scaled)")], font_size=18)).arrange(DOWN, aligned_edge=LEFT,
                                                                                               buff=0.12).to_corner(UL, buff=0.3)
        ql = [z["QL"] for z in sh]
        hmin = [float(np.min(h)) for h in Hs]
        txt = VGroup(MathTex(rf"\text{{total mass}} = {p['mass']:.10f}", font_size=26, color=RV),
                     MathTex(rf"Q_L(10\text{{y}}) = {p['QL']:.3f}", font_size=26, color=VAR),
                     MathTex(rf"\min Q = {p['min_Q']:.1e} \ge 0", font_size=26, color=RV),
                     MathTex(rf"\min\ \text{{Hagan}} = {hmin[-1]:.0f}", font_size=26, color=BAD)).arrange(
            DOWN, aligned_edge=LEFT, buff=0.12).to_corner(DR, buff=0.35)
        self.set_camera_orientation(phi=66 * DEGREES, theta=-115 * DEGREES, zoom=0.82)
        self.add_fixed_in_frame_mobjects(hint, txt)
        self.remove(hint, txt)
        with self.voiceover(
            "Solve it, and watch the density grow in time. Each green slice is the density of the forward rate at one "
            "maturity, a quarter of a year out to ten years, computed by an implicit finite-volume scheme on "
            f"{p['n']} cells. <bookmark mark='a'/> As maturity grows the hump spreads and sinks, and the purple bar "
            "at zero rises: the probability that the rate has been absorbed at zero, "
            f"{100 * p['QL']:.0f} percent by ten years. <bookmark mark='b'/> Now Hagan's 2002 formula on the same "
            "grid, in red. Out to three years it agrees. Beyond that it plunges below the floor: at ten years, "
            f"a density of minus {abs(hmin[-1]):.0f}. <bookmark mark='c'/> The PDE's total probability stays one to "
            "ten decimal places, and its smallest value is positive."
        ) as vo:
            self.play(Create(ax), FadeIn(zero), FadeIn(hint), run_time=1.2)
            self.play(LaggedStart(*[Create(l_) for l_ in pde], lag_ratio=0.3), run_time=3)
            vo.wait_until("a")
            self.play(LaggedStart(*[Create(b_) for b_ in bars], lag_ratio=0.2), run_time=2)
            self.move_camera(theta=-70 * DEGREES, phi=70 * DEGREES, run_time=2)
            vo.wait_until("b")
            self.play(LaggedStart(*[Create(l_) for l_ in hag], lag_ratio=0.3), run_time=3)
            vo.wait_until("c")
            self.play(FadeIn(txt))
        self.move_camera(phi=0, theta=-90 * DEGREES, added_anims=[FadeOut(VGroup(ax, zero, pde, hag, bars)), FadeOut(hint),
                                                                  FadeOut(txt)], run_time=1.5)
        self.clear_scene()

    def compare(self, p):
        K = np.asarray(p["K"])
        g = axes([0, 0.09], [0.15, 0.55], x_length=6.6, y_length=4.0, xlabel=r"strike (rate), 10 years",
                 ylabel=r"implied volatility", xticks=[0, 0.03, 0.06, 0.09], xfmt=lambda u: f"{100 * u:.0f}\\%",
                 yticks=[0.2, 0.3, 0.4, 0.5], yfmt=lambda u: f"{100 * u:.0f}\\%", font_size=16).to_edge(LEFT, buff=0.7)
        lp = curve(g.ax, K, np.clip(np.asarray(p["pde_iv"], float), 0.15, 0.55), RV, stroke_width=3.5)
        lh = curve(g.ax, K, np.clip(np.asarray(p["hagan_iv"], float), 0.15, 0.55), BAD, stroke_width=3)
        leg = legend([(RV, r"arbitrage-free SABR"), (BAD, r"Hagan (2002)")], font_size=18).next_to(g, UP, buff=0.12).align_to(g, LEFT)
        lo = int(np.argmin(np.abs(K - 0.005)))
        side = VGroup(
            MathTex(rf"\text{{ATM: PDE}}\ {100 * p['atm_pde']:.2f}\%,\ \ \text{{Hagan}}\ {100 * p['atm_hagan']:.2f}\%",
                    font_size=28, color=WHITE),
            MathTex(rf"K = 0.5\%:\ \ {100 * p['pde_iv'][lo]:.1f}\%\ \text{{vs}}\ {100 * p['hagan_iv'][lo]:.1f}\%",
                    font_size=28, color=GREY_A),
            wrapped_label(r"near the money the two agree to a fraction of a vol point; at low strikes Hagan's wing is too "
                          r"high: that excess is the negative density's mirror image", 4.4, 19, GREY_A),
        ).arrange(DOWN, aligned_edge=LEFT, buff=0.25).to_edge(RIGHT, buff=0.4)
        src = illustration(rf"$F = 3\%$, $\alpha = {p['params']['alpha']}$, $\beta = {p['params']['beta']}$, "
                           rf"$\rho = {p['params']['rho']}$, $\nu = {p['params']['nu']}$, ten years")
        diff_bp = 1e4 * abs(p["atm_pde"] - p["atm_hagan"])
        with self.voiceover(
            "Price options off the repaired density and convert back to implied volatility. At the money the two "
            f"agree to within {diff_bp:.0f} basis points of volatility, {100 * p['atm_pde']:.1f} against "
            f"{100 * p['atm_hagan']:.1f} percent. <bookmark mark='a'/> In the low-strike wing they part: at a half "
            f"percent strike the PDE says {100 * p['pde_iv'][lo]:.0f} percent, Hagan's formula "
            f"{100 * p['hagan_iv'][lo]:.0f}. Those too-expensive low-strike options are exactly what produced the "
            "negative density. Pause and predict: Hagan's ten-year density integrates to well under one. Where did "
            "the rest go? Into the negative region and the missing tail: an expansion is not a distribution."
        ) as vo:
            self.play(FadeIn(g), FadeIn(src), Create(lp), Create(lh), FadeIn(leg), FadeIn(side[0]), run_time=2)
            vo.wait_until("a")
            self.play(FadeIn(side[1:]))
        self.wait(0.4)
        self.clear_scene()

    def fixes(self):
        c1 = history_card(2008, r"Ob\l\'oj, ``Fine-tune your smile''",
                          r"Corrects the leading term of Hagan's formula for $\beta < 1$ so that it is right in the "
                          r"$T \to 0$ limit (Berestycki--Busca--Florent).", color=QC.IDEA, width=4.1)
        c2 = history_card(2015, r"Antonov, Konikov and Spector, \textit{Wilmott}",
                          r"Free-boundary SABR: $dF = \alpha|F|^\beta dW$, so rates can go below zero, with near-exact "
                          r"pricing. Written for the negative euro rates of 2014--2021.", color=QC.IDEA, width=4.1)
        c3 = history_card(2015, r"Shifted and normal SABR",
                          r"The desk fix for negative rates: model $F + s$ instead of $F$, or quote normal (Bachelier) "
                          r"volatilities with $\beta = 0$.", color=QC.FIRM, width=4.1)
        G = VGroup(c1, c2, c3).arrange(RIGHT, buff=0.3, aligned_edge=UP)
        if G.width > 13.2:
            G.scale_to_fit_width(13.2)
        with self.voiceover(
            "Desks met two more problems and fixed them too. Jan Obłój showed in 2008 that the leading term of "
            "Hagan's formula is slightly wrong for beta below one, and corrected it so the short-maturity limit is "
            "exact. <bookmark mark='a'/> Then euro interest rates went negative in 2014, and a model whose forward "
            "cannot cross zero stopped making sense. Alexandre Antonov, Michael Konikov and Michael Spector "
            "answered with free-boundary SABR, which lets the rate through zero. <bookmark mark='b'/> And the "
            "everyday fix on rate desks was simpler: shift the forward by a constant, or quote normal volatilities."
        ) as vo:
            self.play(FadeIn(c1, shift=UP * 0.2))
            vo.wait_until("a")
            self.play(FadeIn(c2, shift=UP * 0.2))
            vo.wait_until("b")
            self.play(FadeIn(c3, shift=UP * 0.2))
        self.wait(0.4)
        self.clear_scene()

    def bartlett(self):
        rows = [cmath(r"V", r"=", r"C_{\text{BS}}\big(F, K, T, \sigma_B(F, \alpha)\big)", font_size=36, colors={r"V": OPT}),
                cmath(r"\Delta_{\text{Hagan}}", r"=", r"\partial_F C_{\text{BS}} + \partial_\sigma C_{\text{BS}}\ "
                      r"\partial_F\sigma_B", font_size=36, colors={r"\Delta_{\text{Hagan}}": OPT}),
                cmath(r"\mathbb{E}\big[d\alpha \mid dF\big]", r"=", r"\frac{\rho\,\nu}{F^{\beta}}\,dF", font_size=36,
                      colors={r"\mathbb{E}\big[d\alpha \mid dF\big]": VAR}),
                cmath(r"\Delta_{\text{Bartlett}}", r"=", r"\partial_F C_{\text{BS}} + \partial_\sigma C_{\text{BS}}\Big("
                      r"\partial_F\sigma_B + \partial_\alpha\sigma_B\,\frac{\rho\,\nu}{F^{\beta}}\Big)", font_size=34,
                      colors={r"\Delta_{\text{Bartlett}}": OPT})]
        whys = [why(r"the price is Black's formula at SABR's implied vol", 20),
                why(r"the naive delta: move $F$ with $\alpha$ fixed; the smile moves along its backbone", 20),
                why(r"but $\alpha$ is correlated with $F$: regress $d\alpha$ on $dF$ (the same regression as Heston's "
                    r"short skew)", 20),
                why(r"Bartlett (2006): add the expected move of $\alpha$; with $\rho < 0$ the delta of a call is lower. "
                    r"Chapter 17 measures the same idea on bitcoin's real options", 20)]
        step = ladder(self, rows, whys, keep=4, top=2.8, x=-1.0, buff=0.6, edge=6.9)
        with self.voiceover(
            "Finally, the hedge, which is what a desk really uses SABR for. The price is Black's formula at SABR's "
            "implied volatility. <bookmark mark='a'/> Differentiate it with respect to the forward, holding alpha "
            "fixed, and you get Hagan's delta: the direct effect, plus vega times the move of the smile along its "
            "backbone. <bookmark mark='b'/> But alpha is not fixed when the forward moves: the two are correlated, "
            "and the expected move of alpha given a move of the forward is rho nu over F to the beta, times that "
            "move. <bookmark mark='c'/> Add it, and you have Bruce Bartlett's 2006 delta. With negative correlation "
            "a call's delta is smaller than the naive one: when the forward falls, volatility tends to rise, which "
            "cushions the call. Chapter seventeen tests exactly this idea on Bitcoin's real options."
        ) as vo:
            step(0)
            vo.wait_until("a")
            step(1)
            vo.wait_until("b")
            step(2)
            vo.wait_until("c")
            step(3)
        self.wait(0.4)
        self.clear_scene()
