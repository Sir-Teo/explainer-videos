from __future__ import annotations

import numpy as np

from explainer.quant import *  # noqa: F403
from videos.quant.quant5.common import BM, DRIFT, ITO, JUMP, PART, STRAT, load, pause, real_data

GEN = QC.Q


class Frontier(VoiceoverScene):
    def construct(self):
        nz = load("nsde")
        ev = load("nsde_eval")
        self.card()
        self.replay(nz)
        self.measure(ev)
        self.papers()

    def card(self):
        c = chapter_card(18, r"Frontier: learning stochastic dynamics from data", r"Can a network learn an SDE from "
                         r"prices?", lit=(2025,), part=PART)
        with self.voiceover(
            'Chapter eighteen. The frontier: learning stochastic differential equations from data.'
        ):
            self.play(FadeIn(c[0], shift=UP * 0.2), FadeIn(c[1]))
        self.play(FadeOut(c))

    def replay(self, nz):
        seeds = nz["seeds"]
        L = np.array([np.asarray(s["curve"]) for s in seeds])
        steps = np.arange(L.shape[1])
        ck_steps = list(range(0, L.shape[1], 100)) + [L.shape[1] - 1]
        keys = [str(k) for k in ck_steps[:-1]] + [str(L.shape[1])]
        real = np.asarray(nz["real_fan"])
        ymax = float(np.percentile(np.abs(real), 98)) * 1.4

        def frame(i):
            a = axes([0, 32], [-ymax, ymax], x_length=5.0, y_length=3.4, xlabel=r"days",
                     ylabel=r"cumulative standardized return", xticks=[0, 16, 32], yticks=[0], font_size=14)
            t = np.arange(33)
            rf = path_fan(a.ax, t, np.clip(np.concatenate([np.zeros((len(real), 1)), real], 1), -ymax, ymax),
                          color=GREY_B, opacity=0.35)
            fan = np.asarray(seeds[0]["fans"][keys[min(i, len(keys) - 1)]])
            gf = path_fan(a.ax, t, np.clip(np.concatenate([np.zeros((len(fan), 1)), fan], 1), -ymax, ymax), color=GEN,
                          opacity=0.7, stroke_width=1.4)
            return VGroup(a, rf, gf)
        rp = TrainingReplay(steps, L, frame, checkpoints=ck_steps, ylabel=r"mini-batch squared loss",
                            xlabel=r"training step", log_y=True, color=GEN)
        leg = VGroup(
            legend([(GREY_B, r"real: 32-day windows, Bitcoin 2018--2019"), (GEN, r"generated by the neural SDE")], font_size=17),
            wrapped_label(r"loss before updates 0--999; final fan after 1{,}000 updates; three-seed range, not a confidence interval; plots clipped to their limits",
                          12.6, 15, GREY_B),
        ).arrange(DOWN, buff=0.1).to_edge(DOWN, buff=0.25)
        eq = MathTex(r"dY_t = \mu_\theta(t, Y_t)\,dt + \sigma_\theta(t, Y_t)\,dW_t, \qquad "
                     r"\mathcal{L}(\theta) = \big\| \mathbb{E}\,S^{\le 4}(\text{real}) - \mathbb{E}\,S^{\le 4}(\text{gen}) "
                     r"\big\|^2", font_size=26).to_edge(UP, buff=0.3)
        with self.voiceover(
            'Can a network learn the stochastic differential equation itself? Write the drift and the volatility '
            'of a two-dimensional hidden state as two small neural networks, and solve the equation by Euler, '
            "exactly as in chapter five: a neural SDE. Train it on thirty-two-day windows of Bitcoin's daily "
            "returns from 2018 and 2019, a thousand steps per seed, on one processor core. <bookmark mark='a'/> "
            'The loss compares distributions of paths, not single paths: the squared distance between the '
            'expected signatures, up to depth four, of real and generated windows. The signatures here include '
            'time, lead-lag cumulative returns and accumulated squared returns. They provide a training signal '
            'without a discriminator; matching these finite moments does not identify a unique data-generating '
            "SDE. <bookmark mark='b'/> Watch it learn, three seeds as a band. On the left, generated windows, "
            'violet, over real ones, grey: at the start they are almost flat; as training proceeds their spread '
            "and their wiggles grow toward the data's."
        ) as vo:
            self.play(FadeIn(eq))
            vo.wait_until("a")
            self.play(FadeIn(rp), FadeIn(leg))
            vo.wait_until("b")
            rp.play(self, run_time=max(vo.remaining(0.5) - 0.5, 6))
        self.wait(0.4)
        self.clear_scene()

    def measure(self, ev):
        r = ev["real_2020"]
        nm = ev["nsde_mmd_mean"]
        rows = [((
                     'real, 2020 (research test)'
                 ), "--", r["kurtosis"], r["acf_abs"][0], WHITE),
                (r"neural SDE (3 seeds)", nm, ev["nsde_kurt_mean"], ev["nsde_acf_mean"], GEN),
                (r"GBM, fitted", ev["gbm"]["mmd"], ev["gbm"]["kurtosis"], ev["gbm"]["acf_abs"][0], BM),
                (r"bootstrap of 2018--2019 days", ev["bootstrap"]["mmd"], ev["bootstrap"]["kurtosis"],
                 ev["bootstrap"]["acf_abs"][0], DRIFT)]
        head = VGroup(label(r"model", font_size=21, color=GREY_B), label(r"signature distance to 2020", font_size=21,
                                                                         color=GREY_B),
                      label(r"excess kurtosis", font_size=21, color=GREY_B), label(r"lag-1 corr.\ of $|r|$", font_size=21,
                                                                                   color=GREY_B))
        cells = [*head]
        for name, m, k, a, c in rows:
            cells += [label(name, font_size=22, color=c), MathTex(m if isinstance(m, str) else f"{m:.3f}", font_size=28, color=c),
                      MathTex(f"{k:.2f}", font_size=28, color=c), MathTex(f"{a:+.2f}", font_size=28, color=c)]
        grid = VGroup(*cells).arrange_in_grid(rows=len(rows) + 1, cols=4, buff=(0.6, 0.25), col_alignments="lrrr")
        grid.to_edge(UP, buff=0.6)
        if grid.width > 13:
            grid.scale_to_fit_width(13)
        beats_boot = nm < ev["bootstrap"]["mmd"]
        beats_gbm = nm < ev["gbm"]["mmd"]
        kurt_gap = abs(ev["nsde_kurt_mean"] - r["kurtosis"]) < abs(ev["bootstrap"]["kurtosis"] - r["kurtosis"])
        if beats_boot and beats_gbm:
            verdict = ("On the signature distance to 2020 the neural SDE beats both baselines, and its tails are closer "
                       "to 2020's than the bootstrap's." if kurt_gap else
                       "On the signature distance to 2020 the neural SDE beats both baselines, but the bootstrap, which "
                       "reuses real days, gets the fat tails closer.")
        elif beats_gbm:
            verdict = ("The neural SDE beats geometric Brownian motion on the signature distance but not the simple "
                       "bootstrap of past days, though its tails are closer to 2020's." if kurt_gap else
                       "The neural SDE beats geometric Brownian motion on the signature distance, but the simple "
                       "bootstrap of past days beats it there and gets the fat tails closer too.")
        else:
            verdict = ("On the signature distance to 2020 the neural SDE does not beat even geometric Brownian motion, "
                       "though its tails are closer than the bootstrap's." if kurt_gap else
                       "On the signature distance to 2020 the neural SDE does not beat even geometric Brownian motion, "
                       "and the bootstrap gets the fat tails closer.")
        note_ = wrapped_label((
                                  (
                                      (
                                          'overlapping 32-day windows: 2020 research test; window-pooled moments; 2018--2019 training '
                                          'statistics; depth-4 signature distance; not the sealed post-2020 hold-out'
                                      )
                                  )
                              ), 11.0, 18, GREY_B)
        note_.next_to(grid, DOWN, buff=0.4)
        pc, ans = pause(r"A generator matches the expected signature to depth 4. Does it match the law of the 32-day "
                        r"maximum?", r"Not necessarily: the expected signature determines the law only at all depths and "
                        r"under growth conditions (Chevyrev and Lyons 2016).", width=8.4, font_size=20)
        VGroup(pc, ans).arrange(DOWN, aligned_edge=LEFT, buff=0.1).to_edge(DOWN, buff=0.3)
        with self.voiceover(
            f"Then evaluate on 2020, which was excluded from gradient training. This is a chronological research split, not the series’ sealed post-2020 hold-out. The overlapping windows are dependent, and three seeds measure optimizer variation rather than a confidence interval. Three numbers: the signature distance to 2020's windows; the excess kurtosis of daily returns, the fat tails; and the correlation of absolute returns from one day to the next, the signature of volatility clustering. Two baselines at equal data: geometric Brownian motion fitted to the same two years, and a bootstrap that redraws past days at random, which keeps the tails but destroys any clustering. <bookmark mark='a'/> {verdict} A small generator trained in minutes is not yet a market; the papers that follow train much larger ones. <bookmark mark='b'/> A pause: if a generator matches the expected signature up to depth four, does it match the distribution of the largest move in a window? <bookmark mark='c'/> Not necessarily: the expected signature pins down the law only with all its levels, and under growth conditions, as Chevyrev and Lyons showed."
        ) as vo:
            self.play(FadeIn(VGroup(*cells[:4])), FadeIn(VGroup(*cells[4:8])))
            vo.wait_until("a")
            self.play(LaggedStart(*[FadeIn(VGroup(*cells[4 * k:4 * k + 4])) for k in range(2, len(rows) + 1)],
                                  lag_ratio=0.4), FadeIn(note_))
            vo.wait_until("b")
            self.play(FadeIn(pc))
            vo.wait_until("c")
            self.wait(0.8)
            self.play(FadeIn(ans))
        self.wait(0.4)
        self.clear_scene()

    def papers(self):
        items = [
            (r"Issa, Horvath, Lemercier and Salvi (NeurIPS 2023)", r"neural SDEs trained with signature-kernel scoring "
             r"rules instead of a GAN's discriminator; our loss is the linear-kernel cousin"),
            (r"Cuchiero, Gazzani, M\"oller and Svaluto-Ferro (\textit{Math.\ Finance} 2025)", r"the price as a linear "
             r"function of a signature: joint SPX and VIX calibration"),
            (r"Walker, McLeod, Qin, Cheng, Li and Lyons (ICML 2024)", r"log-signatures and Lie brackets inside neural "
             r"controlled differential equations"),
            (r"Cont and Das (\textit{Sankhy\=a B} 2024); Guyon and Lekeufack (\textit{QF} 2023)", r"rough volatility: fact or "
             r"artefact; volatility is mostly path-dependent"),
            (r"Bayer, dos Reis, Horvath and Oberhauser (eds.), \textit{Signature Methods in Finance}; Cass and Salvi, "
             r"lecture notes (2024)", r"open references for chapters 16 and 18"),
            (r"Degenne, Ledvinka, Marion and Pfaffelhuber (2025)", r"Brownian motion constructed and its continuity proved "
             r"in the Lean theorem prover: chapter 1, checked by a machine"),
            (r"Gierjatowicz, Sabate-Vidales, \v{S}i\v{s}ka, Szpruch and \v{Z}uri\v{c} (\textit{J.\ Comput.\ Finance}); "
             r"Kidger et al.\ (ICML 2021)", r"the earlier neural SDEs: robust pricing bounds; SDEs as GANs"),
        ]
        rows = VGroup(*[VGroup(label(a, font_size=19, color=ITO), wrapped_label(b, 12.0, 17, GREY_A)).arrange(
            DOWN, aligned_edge=LEFT, buff=0.04) for a, b in items]).arrange(DOWN, aligned_edge=LEFT, buff=0.16)
        head = label(r"The frontier, 2023--2026", font_size=32).to_edge(UP, buff=0.3)
        rows.next_to(head, DOWN, buff=0.3)
        if rows.height > 6.6:
            rows.scale_to_fit_height(6.6)
        rows.to_edge(LEFT, buff=0.5)
        with self.voiceover(
            'Where the research is. Issa, Horvath, Lemercier and Salvi train neural SDEs with scoring rules built'
            ' on the signature kernel, which compares all levels of the signature at once: our loss is its '
            'truncated, linear cousin, and their method needs no adversary. Cuchiero and coauthors write option '
            'prices as linear functions of the signature of a polynomial diffusion and calibrate to the S and P '
            'and the VIX at the same time, a problem classical models struggle with. Walker and coauthors put '
            "log-signatures and their Lie brackets inside sequence models. <bookmark mark='a'/> The roughness "
            "debate of chapter fifteen continues, with Cont and Das on one side, and Guyon and Lekeufack's "
            'finding that index volatility is mostly driven by past returns. Two open books cover signatures in '
            "finance. <bookmark mark='b'/> And in 2025 Degenne, Ledvinka, Marion and Pfaffelhuber formalized the "
            "construction of Brownian motion in the Lean theorem prover: chapter one's theorem, checked by a "
            'computer, with stochastic integrals announced as next.'
        ) as vo:
            self.play(FadeIn(head), LaggedStart(*[FadeIn(r_) for r_ in rows[:3]], lag_ratio=0.4))
            vo.wait_until("a")
            self.play(LaggedStart(*[FadeIn(r_) for r_ in rows[3:5]], lag_ratio=0.4))
            vo.wait_until("b")
            self.play(LaggedStart(*[FadeIn(r_) for r_ in rows[5:]], lag_ratio=0.4))
        self.wait(0.4)
        self.clear_scene()
