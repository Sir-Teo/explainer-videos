    def mechanics(self):
        rows = [cmath(r"\text{volume-targeted selling}", r"\Rightarrow", r"\text{more volume} \Rightarrow \text{faster selling}",
                      font_size=30, colors={r"\text{volume-targeted selling}": BAD}),
                cmath(r"\text{HFTs}", r":", r"\text{bought, then sold to each other: hot potato}", font_size=32,
                      colors={r"\text{HFTs}": DEALER_C}),
                cmath(r"\text{liquidity}", r"\to", r"0:\ \text{quotes pulled, stub quotes hit}", font_size=32,
                      colors={r"\text{liquidity}": BAD})]
        whys = [why('a participation algorithm can react to rising measured volume; turnover generated by its own executions is endogenous and does not establish new independent capacity'),
                why(r"Kirilenko, Kyle, Samadi and Tuzun (2017): high-frequency traders did not cause the crash, but traded "
                    r"inventory back and forth, raising volume, and then withdrew"),
                why(r"with no one willing to hold inventory, the book emptied down to placeholder quotes far from any value")]
        step = ladder(self, rows, whys, keep=3, top=2.6, x=-0.3, buff=0.55, edge=6.9)
        self.add(rows[0], whys[0])
        with self.voiceover(
            "The reports describe interacting mechanisms. <bookmark mark='a'/> A volume-targeting program can accelerate when measured turnover rises. If its own trading contributes, the volume clock is endogenous; that does not create independent liquidity. <bookmark mark='b'/> Kirilenko and coauthors describe high-frequency intermediaries passing inventory rapidly and changing their demand during the episode. This is evidence about a dated event, not proof that one class of traders universally causes or prevents crashes. <bookmark mark='c'/> Thinner books and distant placeholder quotes amplified some executions. Causality involves market conditions, other participants and the order design together."
        ) as vo:
            step(0)
            vo.wait_until("a")
            self.wait(0.1)
            vo.wait_until("b")
            step(1)
            vo.wait_until("c")
            step(2)
        self.wait(0.5)
        self.clear_scene()

