    def btc_days(self, d):
        import numpy as np
        lam = np.asarray(d["lambda"], float)
        x = np.arange(len(lam))
        ok = np.isfinite(lam)
        top = float(np.ceil(np.nanmax(lam) / 5) * 5)
        bottom = min(0.0, float(np.floor(np.nanmin(lam) / 5) * 5))
        g = axes([0, len(lam)], [bottom, top], x_length=8.2, y_length=4.0, xlabel=r"BTCUSDT, 2021--2024, by day",
                 ylabel=r"$\hat\lambda$, bp per \$1m", xticks=[0, 365, 730, 1095, 1461], yticks=[0, top / 2, top],
                 xfmt=lambda v: str(2021 + int(round(v / 365.25))), yfmt=lambda v: f"{v:.0f}", font_size=14)
        g.move_to(LEFT * 0.6 + DOWN * 0.3)
        ax = g.ax
        c1 = curve(ax, x[ok], lam[ok], FLOW_C, stroke_width=1.2)
        med = DashedLine(ax.c2p(0, d["median"]), ax.c2p(len(lam), d["median"]), color=GREY_B, stroke_width=1.5)
        t5 = d["top"]
        st = VGroup(*[label(rf"{t_['date']}: {t_['lambda']:.1f}", font_size=15, color=BAD) for t_ in t5[:4]])
        st.arrange(DOWN, aligned_edge=LEFT, buff=0.08).to_corner(UR, buff=0.35)
        r1 = d["top"][0]
        ratio = r1["lambda"] / d["median"]
        self.add(g, c1, med)
        with self.voiceover(
            f"""Daily same-bar regression slopes in the saved archive. <bookmark mark='a'/> The median is {d['median']:.1f} basis points per million dollars. Every finite saved slope appears without percentile clipping. <bookmark mark='b'/> The largest selected slope is {ratio:.1f} times the median. Its correlation with daily volatility is {d['corr_vol']:.2f}, and with dollar turnover {d['corr_dv']:.2f}. The highlighted dates were ranked after observing the sample. These descriptive associations do not identify vanished executable depth, a liquidation mechanism or a forecast available before stress. Daily gaps and omitted costs remain."""
        ) as vo:
            self.play(FadeIn(g), Create(med))
            vo.wait_until("a")
            self.play(Create(c1), run_time=2.5)
            vo.wait_until("b")
            self.play(FadeIn(st))
        self.wait(0.4)
        self.clear_scene()

