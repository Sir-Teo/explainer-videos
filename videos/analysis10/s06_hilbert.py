def hull(points):
    """Convex hull of complex points (monotone chain), counter-clockwise."""
    P = sorted({(round(p.real, 12), round(p.imag, 12)) for p in points})

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lo, hi = [], []
    for p in P:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(P):
        while len(hi) >= 2 and cross(hi[-2], hi[-1], p) <= 0:
            hi.pop()
        hi.append(p)
    return np.array([complex(*p) for p in lo[:-1] + hi[:-1]])


class HilbertOperators(VoiceoverScene):
    def construct(self):
        self.card()
