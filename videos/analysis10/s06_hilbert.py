    def numerical_range(self):
        d = load("numrange")
        pts, ev, vals = d["pts"], d["ev"], d["vals"]
        nd = load("normal")
        lam = nd["lam"]
        ax = square_axes([-2.0, 2.6, 1], [-2.0, 2.0, 1], 1.05).move_to([-3.6, -0.3, 0])
        bx = square_axes([-2.0, 1.6, 1], [-1.8, 1.6, 1], 1.05).move_to([2.2, -0.3, 0])
        region = Polygon(*[ax.c2p(p.real, p.imag) for p in pts[:-1]], color=C.INNER, stroke_width=3, fill_color=C.INNER,
                         fill_opacity=0.18)
        samp = VGroup(*[Dot(ax.c2p(v.real, v.imag), radius=0.02, color=C.INNER) for v in vals])
        evd = VGroup(*[Dot(ax.c2p(l_.real, l_.imag), radius=0.07, color=C.SPECTRUM) for l_ in ev])
        hA = MathTex(r"T: \text{ upper triangular, not normal}", font_size=24).next_to(ax, UP, buff=0.1)
        # a normal matrix: the numerical range is the convex hull of the eigenvalues
        H = hull(lam)
        poly = Polygon(*[bx.c2p(p.real, p.imag) for p in H], color=C.INNER, stroke_width=3, fill_color=C.INNER,
                       fill_opacity=0.18)
        rng = np.random.default_rng(6)
        w = rng.dirichlet(np.ones(6) * 0.5, 400)  # <Ax, x> = sum |c_i|^2 l_i: a random convex combination
        nvals = w @ lam
        nsamp = VGroup(*[Dot(bx.c2p(v.real, v.imag), radius=0.02, color=C.INNER) for v in nvals])
        nev = VGroup(*[Dot(bx.c2p(l_.real, l_.imag), radius=0.07, color=C.SPECTRUM) for l_ in lam])
        hB = MathTex(r"A: \text{ normal}", font_size=24).next_to(bx, UP, buff=0.1)
        # convexity, and containment of the eigenvalues, checked by support functions in the compute step
        rows = VGroup(
            MathTex(r"W(T) = \{\langle Tx, x\rangle : \|x\| = 1\}", font_size=28, color=C.INNER),
            label(r"convex (Toeplitz--Hausdorff); \ $\sigma(T) \subset \overline{W(T)}$", font_size=22),
            label(r"normal: \ $\overline{W} = $ the convex hull of $\sigma$; \ self-adjoint: \ $W \subset \mathbb R$",
                  font_size=22, color=C.EPS),
            label(r"\textbf{FA 12.16} \ (Fuglede--Putnam) \ $NT = TN$ $\Rightarrow$ $N^*T = TN^*$ \ for normal $N$",
                  font_size=20, color=GREY_A),
        ).arrange(DOWN, buff=0.1).to_edge(DOWN, buff=0.25)
        for r_ in rows:
            if r_.width > 13:
                r_.width = 13
        head = label(r"Where $\langle Tx, x\rangle$ can land", font_size=34).to_edge(UP, buff=0.25)
        with self.voiceover(
            "<bookmark mark='a'/> The numerical range collects the values of T x against x, for unit vectors x. "
            "For this non-normal matrix it's a convex region, traced by its supporting lines, and it contains the "
            "eigenvalues, but it's much bigger than they are. <bookmark mark='b'/> For a normal matrix, it's exactly "
            "the convex hull of the eigenvalues: T x against x is just an average of eigenvalues, weighted by the "
            "squared coordinates of x. <bookmark mark='c'/> And for a self-adjoint operator it's a real interval. "
            "Normal operators are the ones whose geometry is controlled by their spectrum."
        ) as vo:
            vo.wait_until("a")
            self.play(FadeIn(head), Create(ax), FadeIn(hA), FadeIn(rows[0]))
            self.play(FadeIn(samp), DrawBorderThenFill(region), FadeIn(evd), FadeIn(rows[1]), run_time=2.0)
            vo.wait_until("b")
            self.play(Create(bx), FadeIn(hB), FadeIn(nsamp), DrawBorderThenFill(poly), FadeIn(nev), run_time=2.0)
            vo.wait_until("c")
            self.play(FadeIn(rows[2:]))
        self.wait(0.4)
        self.clear_scene()
