    # ------------------------------------------------------------------
    def card(self):
        card = chapter_card(5, r"Operators on Hilbert space", r"What does the adjoint buy?", lit=(1907,), part=10)
        with self.voiceover("Chapter five: operators on Hilbert space, where every operator has an adjoint."):
            self.play(FadeIn(card[0], shift=UP * 0.2), FadeIn(card[1]))
        self.play(FadeOut(card))

    # ------------------------------------------------------------------
    def adjoints(self):
        card = dictionary_card(r"matrices", r"operators on $H$", [
            (r"transpose-conjugate $A^*$", r"$\langle Tx, y\rangle = \langle x, T^*y\rangle$"),
            (r"Hermitian: \ $A = A^*$", r"self-adjoint: \ $T = T^*$"),
            (r"unitary: \ $A^*A = AA^* = I$", r"unitary: \ onto isometries"),
            (r"normal: \ $A^*A = AA^*$", r"normal: \ $T^*T = TT^*$"),
            (r"orthogonal projection", r"$P = P^2 = P^*$"),
        ], font_size=24)
        card.scale_to_fit_width(11.5).move_to(UP * 0.5)
        rng = np.random.default_rng(8)
        worst = 0.0
        for _ in range(300):
            T = rng.normal(size=(7, 7)) + 1j * rng.normal(size=(7, 7))
            worst = max(worst, abs(np.linalg.norm(T.conj().T @ T, 2) / np.linalg.norm(T, 2) ** 2 - 1))
        assert worst < 1e-12
        rows = VGroup(
            MathTex(r"\|T^*T\| = \|T\|^2: \quad \|Tx\|^2 = \langle T^*Tx, x\rangle \le \|T^*T\|\,\|x\|^2", font_size=28,
                    color=C.EPS),
            MathTex(rf"\text{{300 random }} 7 \times 7: \ \text{{largest deviation }} {sci(worst, 0)}", font_size=22,
                    color=GREY_A),
            label(r"so $B(H)$ is a $C^*$-algebra: \ chapter 4's theory applies to it", font_size=24),
        ).arrange(DOWN, buff=0.12).to_edge(DOWN, buff=0.3)
        head = label(r"\textbf{FA 12.1--12.15} \ the adjoint", font_size=34).to_edge(UP, buff=0.3)
        with self.voiceover(
            "<bookmark mark='a'/> On a Hilbert space every bounded operator has an adjoint, defined by moving it "
            "across the inner product. The matrix words all survive: self-adjoint, unitary, normal, projection. "
            "<bookmark mark='b'/> And one identity makes everything work: the norm of T star T is the square of the "
            "norm of T, because the size of T x squared is the inner product of T star T x with x. "
            "<bookmark mark='c'/> So the bounded operators form a C-star algebra, and Gelfand's theory applies to "
            "the algebra generated by any normal operator."
        ) as vo:
            vo.wait_until("a")
            self.play(FadeIn(head), FadeIn(card.titles))
            self.play(LaggedStart(*[AnimationGroup(FadeIn(r_), FadeIn(a_)) for r_, a_ in zip(card.rows, card.arrows)],
                                  lag_ratio=0.4), run_time=4.0)
            vo.wait_until("b")
            self.play(FadeIn(rows[:2]))
            vo.wait_until("c")
            self.play(FadeIn(rows[2]))
        self.wait(0.3)
        self.clear_scene()

