    def projection(self):
        ax = square_axes([-2.6, 2.6, 1], [-2.0, 2.0, 1], 1.1).move_to([-3.4, -0.4, 0])
        u = np.array([math.cos(0.5), math.sin(0.5)])
        P = np.outer(u, u)
        assert np.allclose(P @ P, P) and np.allclose(P, P.T)
        line = Line(ax.c2p(*(-2.6 * u)), ax.c2p(*(2.6 * u)), color=C.INNER, stroke_width=3)
        ll = MathTex(r"M = \operatorname{ran} P", font_size=24, color=C.INNER).next_to(ax.c2p(*(1.5 * u)), UL, buff=0.05)
        rng = np.random.default_rng(3)
        pts = rng.uniform(-1.8, 1.8, (14, 2))
        dots = VGroup(*[Dot(ax.c2p(*p), radius=0.05, color=C.FUNC) for p in pts])
        shadows = VGroup(*[Dot(ax.c2p(*(P @ p)), radius=0.05, color=C.INNER) for p in pts])
        drops = VGroup(*[DashedLine(ax.c2p(*p), ax.c2p(*(P @ p)), color=GREY_B, stroke_width=1.5) for p in pts])
        # residuals are orthogonal to the line
        assert np.allclose([(p - P @ p) @ u for p in pts], 0)
        rows = VGroup(
            label(r"an orthogonal projection: \ every point drops to its nearest point in $M$", font_size=24),
            MathTex(r"P^2 = P \ (\text{a shadow's shadow is itself}), \quad P^* = P", font_size=28),
            MathTex(r"x - Px \perp M, \qquad \|x\|^2 = \|Px\|^2 + \|x - Px\|^2", font_size=28, color=C.EPS),
            label(r"Part 6's nearest-point theorem, \ seen as an operator", font_size=22, color=GREY_A),
            label(r"projections will be the building blocks of the spectral theorem", font_size=24, color=C.SPECTRUM),
        ).arrange(DOWN, aligned_edge=LEFT, buff=0.16).move_to([3.4, -0.4, 0])
        for r_ in rows:
            if r_.width > 6.6:
                r_.width = 6.6
        rows.arrange(DOWN, aligned_edge=LEFT, buff=0.16).move_to([3.4, -0.4, 0])
        head = label(r"Projections are shadows", font_size=34).to_edge(UP, buff=0.3)
        with self.voiceover(
            "<bookmark mark='a'/> The simplest self-adjoint operators are the projections. Each point drops "
            "perpendicularly onto a closed subspace, its nearest point there, from Part 6. "
            "<bookmark mark='b'/> Projecting twice changes nothing, and the leftover is perpendicular, so "
            "Pythagoras splits the length. <bookmark mark='c'/> Projections will be the bricks of the spectral "
            "theorem: diagonalizing an operator will mean writing it as a sum, or an integral, of numbers times "
            "projections."
        ) as vo:
            vo.wait_until("a")
            self.play(FadeIn(head), Create(ax), Create(line), FadeIn(ll), FadeIn(dots), FadeIn(rows[0]))
            self.play(LaggedStart(*[Create(d_) for d_ in drops], lag_ratio=0.1),
                      LaggedStart(*[TransformFromCopy(a_, b_) for a_, b_ in zip(dots, shadows)], lag_ratio=0.1),
                      run_time=2.5)
            vo.wait_until("b")
            self.play(FadeIn(rows[1:4]))
            vo.wait_until("c")
            self.play(FadeIn(rows[4]))
        self.wait(0.3)
        self.clear_scene()

