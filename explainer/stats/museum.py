def sunspots() -> tuple:
    """Yearly sunspot numbers 1700-2008 (the version statsmodels ships), as (years, numbers).  Yule (1927) fitted his
    autoregression to the years 1749-1924."""
    import statsmodels.api as sm

    d = sm.datasets.sunspots.load_pandas().data
    return d["YEAR"].to_numpy().astype(int), d["SUNACTIVITY"].to_numpy().astype(float)


def co2_monthly() -> tuple:
    """Mauna Loa CO2 (ppm), Keeling's record as statsmodels ships it (weekly, March 1958 - December 2001), averaged to
    months with gaps filled by interpolation: (decimal year, ppm), from January 1959 to December 2001."""
    import statsmodels.api as sm

    s = sm.datasets.co2.load_pandas().data["co2"]
    m = s.resample("MS").mean().interpolate()
    m = m[(m.index.year >= 1959)]
    t = m.index.year + (m.index.month - 0.5) / 12
    return t.to_numpy(), m.to_numpy()


def federalist() -> dict:
    """The *Federalist* papers as word counts (tools/federalist_counts.py, from Project Gutenberg's ebook 18): for each
    of the 85 papers, ``no``, ``author`` (HAMILTON, MADISON, JAY, JOINT or DISPUTED, with the standard 12 disputed
    papers 49-58, 62 and 63 that Mosteller & Wallace, 1964, studied), ``n_words`` and ``counts`` of Mosteller &
    Wallace's 70 function words and some marker words (upon, whilst, while, enough, although, ...)."""
    import json
    from pathlib import Path

    d = json.loads((Path(__file__).parent / "data" / "federalist_counts.json").read_text())
    disputed = set(range(49, 59)) | {62, 63}
    for p in d["papers"]:
        a = p["author"]
        p["author"] = "DISPUTED" if p["no"] in disputed else ("JOINT" if "AND" in a else a)
    return d


def nhanes() -> dict:
    """NHANES 2017-2018 (CDC/NCHS, public domain), as extracted by ``tools/nhanes_extract.py``: one entry per column
    (numpy float arrays, NaN where missing) for the 5,533 examined participants aged 18+, with the design variables
    ``wt_mec``, ``wt_diet1``, ``strata`` and ``psu``, blood-pressure readings ``sbp1..4``/``dbp1..4``, ``bmi``, two
    24-hour dietary recalls (``na1``/``na2`` sodium in mg, ``kcal1``/``kcal2``, ``k1`` potassium, ``diet1_ok``/
    ``diet2_ok`` reliability codes) and the questions ``told_high`` and ``bp_meds``.  Part 20's capstone."""
    import csv
    from pathlib import Path

    import numpy as np

    with open(Path(__file__).parent / "data" / "nhanes_bp.csv", newline="") as f:
        rows = list(csv.reader(f))
    head, body = rows[0], rows[1:]
    return {h: np.array([float(r[j]) if r[j] != "" else np.nan for r in body]) for j, h in enumerate(head)}


