"""Defeasible reasoning, made computable (Part 14).

* Reiter's default logic (1980): extensions of a default theory, found by brute force over the defaults and checked
  for groundedness (Tweety; the Nixon diamond).
* Pearl's System Z (1990), which computes rational closure (Lehmann and Magidor 1992): the Z-partition of a set of
  defaults, the ranking of worlds it induces, and the entailment A |~ B; with the drowning problem.
* KLM (Kraus, Lehmann and Magidor 1990): the rules of System P and rational monotonicity, checked on a ranked and on
  a merely preferential model.
* Dung's abstract argumentation (1995): conflict-free, admissible, complete, grounded, preferred and stable
  extensions, and the grounded labelling (in, out, undecided).
"""

from __future__ import annotations

import itertools

from . import prop
from .revision import P, valuation, worlds


# ---------------------------------------------------------------------------
# Reiter's default logic
# ---------------------------------------------------------------------------
def _ent(fs, g) -> bool:
    return prop.entails([prop.parse(f) for f in fs], prop.parse(g))[0]


def _cons(fs) -> bool:
    return prop.satisfiable([prop.parse(f) for f in fs])


def extensions(W: list[str], D: list[tuple[str, str, str]]) -> list[dict]:
    """``D``: defaults (prerequisite, justification, consequent). An extension is generated by a set G of defaults
    when, with E = Cn(W + consequents of G), the defaults that fire in a grounded order, given E, are exactly G."""
    out = []
    for r in range(len(D) + 1):
        for G in itertools.combinations(range(len(D)), r):
            E = list(W) + [D[i][2] for i in G]
            if not _cons(E):
                continue
            # grounded reconstruction: apply defaults whose justification is consistent with E, from W upwards
            T, used = list(W), set()
            changed = True
            while changed:
                changed = False
                for i, (pre, just, cons) in enumerate(D):
                    if i in used:
                        continue
                    if _ent(T, pre) and _cons(E + [just]):
                        T.append(cons)
                        used.add(i)
                        changed = True
            if used == set(G):
                out.append({"defaults": sorted(G), "consequents": [D[i][2] for i in G]})
    return out


def tweety() -> dict:
    D = [("b", "f", "f")]
    W_bird = ["b", "p -> b", "p -> ~f"]
    W_peng = ["p", "p -> b", "p -> ~f"]
    return {"bird": extensions(W_bird, D), "penguin": extensions(W_peng, D),
            "penguin_flies": [_ent(W_peng + e["consequents"], "f") for e in extensions(W_peng, D)]}


def nixon() -> dict:
    D = [("q", "pa", "pa"), ("r", "~pa", "~pa")]
    return {"extensions": extensions(["q", "r"], D)}


# ---------------------------------------------------------------------------
# System Z and rational closure
# ---------------------------------------------------------------------------
def z_partition(defaults: list[tuple[str, str]], atoms) -> list[list[int]]:
    """Defaults a => b. A default is tolerated by a set if some world verifies it (a and b) and falsifies none of the
    set's material counterparts."""
    rest = list(range(len(defaults)))
    W = worlds(atoms)
    layers = []
    while rest:
        mat = [prop.parse(f"({defaults[i][0]}) -> ({defaults[i][1]})") for i in rest]
        layer = []
        for i in rest:
            a, b = prop.parse(defaults[i][0]), prop.parse(defaults[i][1])
            ok = any(prop.evaluate(a, valuation(w, atoms)) and prop.evaluate(b, valuation(w, atoms)) and
                     all(prop.evaluate(m, valuation(w, atoms)) for m in mat) for w in W)
            if ok:
                layer.append(i)
        if not layer:
            raise ValueError("inconsistent defaults")
        layers.append(layer)
        rest = [i for i in rest if i not in layer]
    return layers


def z_rank(defaults, atoms) -> dict:
    layers = z_partition(defaults, atoms)
    z = {i: k for k, layer in enumerate(layers) for i in layer}
    rank = {}
    for w in worlds(atoms):
        v = valuation(w, atoms)
        bad = [z[i] for i, (a, b) in enumerate(defaults)
               if prop.evaluate(prop.parse(a), v) and not prop.evaluate(prop.parse(b), v)]
        rank[w] = 0 if not bad else 1 + max(bad)
    return rank


def nm_entails(rank: dict, a: str, b: str, atoms) -> bool:
    A = P(a, atoms)
    if not A:
        return True
    m = min(rank[w] for w in A)
    B = P(b, atoms)
    return all(w in B for w in A if rank[w] == m)


def penguins() -> dict:
    """Birds fly, penguins are birds, penguins don't fly, birds have wings. System Z gets the first three right, and
    is silent on whether penguins have wings: the drowning problem."""
    atoms = ("b", "f", "p", "w", "r")
    defaults = [("b", "f"), ("p", "b"), ("p", "~f"), ("b", "w")]
    rank = z_rank(defaults, atoms)
    queries = [("b", "f"), ("p", "~f"), ("p", "b"), ("b & r", "f"), ("p", "w"), ("p", "~w")]
    return {"defaults": defaults, "layers": z_partition(defaults, atoms),
            "queries": [{"a": a, "b": b, "holds": nm_entails(rank, a, b, atoms)} for a, b in queries]}


# ---------------------------------------------------------------------------
# KLM: System P and rational monotonicity on two small models
# ---------------------------------------------------------------------------
def _props(W):
    return [frozenset(c) for r in range(1, len(W) + 1) for c in itertools.combinations(W, r)]


def check_klm(W, below) -> dict:
    """``below(u, v)``: u is strictly more normal than v. A |~ B iff the minimal A-worlds are all B-worlds."""
    W = list(W)
    props = _props(W)
    allW = frozenset(W)

    def mins(A):
        return frozenset(u for u in A if not any(below(v, u) for v in A))

    def nm(A, B):
        return mins(A) <= B
    res = {k: None for k in ("And", "Or", "Cautious Monotonicity", "Cut", "Rational Monotonicity", "Monotonicity")}
    for A in props:
        for B in props:
            for C in props:
                if res["And"] is None and nm(A, B) and nm(A, C) and not nm(A, B & C):
                    res["And"] = (A, B, C)
                if res["Or"] is None and nm(A, C) and nm(B, C) and not nm(A | B, C):
                    res["Or"] = (A, B, C)
                AB = A & B
                if AB:
                    if res["Cautious Monotonicity"] is None and nm(A, B) and nm(A, C) and not nm(AB, C):
                        res["Cautious Monotonicity"] = (A, B, C)
                    if res["Cut"] is None and nm(AB, C) and nm(A, B) and not nm(A, C):
                        res["Cut"] = (A, B, C)
                    if res["Rational Monotonicity"] is None and nm(A, C) and not nm(A, allW - B) and \
                            not nm(AB, C):
                        res["Rational Monotonicity"] = (A, B, C)
                    if res["Monotonicity"] is None and nm(A, C) and not nm(AB, C):
                        res["Monotonicity"] = (A, B, C)
    return {k: {"holds": v is None, "counterexample": None if v is None else [sorted(x) for x in v]}
            for k, v in res.items()}


def klm_table() -> dict:
    ranked = {"a": 0, "b": 1, "c": 1, "d": 2}
    partial = {("a", "b")}                                  # a below b; c incomparable with both

    return {"ranked": check_klm(list(ranked), lambda u, v: ranked[u] < ranked[v]),
            "preferential": check_klm(["a", "b", "c"], lambda u, v: (u, v) in partial)}


# ---------------------------------------------------------------------------
# Dung's abstract argumentation
# ---------------------------------------------------------------------------
class AF:
    def __init__(self, args, attacks):
        self.args = list(args)
        self.att = set(tuple(x) for x in attacks)

    def attacks(self, S, a) -> bool:
        return any((b, a) in self.att for b in S)

    def conflict_free(self, S) -> bool:
        return not any((a, b) in self.att for a in S for b in S)

    def defends(self, S, a) -> bool:
        return all(self.attacks(S, b) for b in self.args if (b, a) in self.att)

    def F(self, S):
        return frozenset(a for a in self.args if self.defends(S, a))

    def admissible(self, S) -> bool:
        return self.conflict_free(S) and all(self.defends(S, a) for a in S)

    def subsets(self):
        return [frozenset(c) for r in range(len(self.args) + 1) for c in itertools.combinations(self.args, r)]

    def complete(self):
        return [S for S in self.subsets() if self.admissible(S) and self.F(S) == S]

    def grounded(self):
        S = frozenset()
        while True:
            T = self.F(S)
            if T == S:
                return S
            S = T

    def preferred(self):
        adm = [S for S in self.subsets() if self.admissible(S)]
        return [S for S in adm if not any(S < T for T in adm)]

    def stable(self):
        return [S for S in self.subsets() if self.conflict_free(S) and
                all(self.attacks(S, a) for a in self.args if a not in S)]

    def labelling(self, S=None):
        S = self.grounded() if S is None else S
        lab = {}
        for a in self.args:
            if a in S:
                lab[a] = "in"
            elif self.attacks(S, a):
                lab[a] = "out"
            else:
                lab[a] = "undec"
        return lab

    def summary(self) -> dict:
        srt = lambda xs: sorted(sorted(S) for S in xs)  # noqa: E731
        return {"grounded": sorted(self.grounded()), "preferred": srt(self.preferred()), "stable": srt(self.stable()),
                "complete": srt(self.complete()), "labelling": self.labelling()}


EXAMPLES = {
    "reinstatement": AF(["a", "b", "c"], [("b", "a"), ("c", "b")]),
    "mutual attack": AF(["a", "b"], [("a", "b"), ("b", "a")]),
    "odd cycle": AF(["a", "b", "c"], [("a", "b"), ("b", "c"), ("c", "a")]),
    "trial": AF(["P1", "D1", "P2", "D2", "P3"], [("D1", "P1"), ("P2", "D1"), ("D2", "P2"), ("P3", "D2")]),
    "trial, disputed": AF(["P1", "D1", "P2", "D2", "P3", "D3"],
                          [("D1", "P1"), ("P2", "D1"), ("D2", "P2"), ("P3", "D2"), ("D3", "P3"), ("P3", "D3")]),
}


def argue_table() -> dict:
    return {k: v.summary() for k, v in EXAMPLES.items()}
