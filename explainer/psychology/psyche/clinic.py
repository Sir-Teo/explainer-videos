def avoidance(acquire: int = 20, extinguish: int = 60, alpha: float = 0.25, ext_alpha: float = 0.08,
              prevent: bool = False,
              slope: float = 10.0, threshold: float = 0.3, seed: int = 0) -> dict:
    """Mowrer's two factors on a Rescorla-Wagner learner.  Fear V of a warning signal is acquired over ``acquire``
    pairings with shock.  Then shocks stop.  On each extinction trial the learner avoids with probability
    sigmoid(slope (V - threshold)); an avoided trial ends the signal early, so the learner never finds out that no
    shock was coming and V does not change (avoidance is reinforced by relief instead); at most 95% of trials are
    avoided.  Only trials it does not
    avoid extinguish fear, at the slower rate ``ext_alpha``.  With ``prevent`` (exposure with response prevention) every trial is a full exposure."""
    rng = np.random.default_rng(seed)
    V = 0.0
    fear, avoided = [], []
    for _ in range(acquire):
        V += alpha * (1.0 - V)
        fear.append(V)
        avoided.append(False)
    for _ in range(extinguish):
        av = (not prevent) and rng.random() < 0.95 * _sig(slope * (V - threshold))
        if not av:
            V += ext_alpha * (0.0 - V)
        fear.append(V)
        avoided.append(bool(av))
    return {"fear": np.array(fear), "avoided": np.array(avoided), "acquire": acquire}


def renewal(acquire: int = 15, extinguish: int = 30, alpha: float = 0.25, beta: float = 0.2) -> dict:
    """Bouton's account: extinction is new, context-bound learning.  Excitation E (signal -> shock) is learned in
    context A and generalizes; inhibition I (signal -> no shock) is learned during extinction in context B and is
    expressed only in B.  Fear = E - I x [in context B].  Returns fear over acquisition and extinction, and at test
    in B (where extinction happened), in A (renewal) and in a new context C."""
    E = I = 0.0
    trace = []
    for _ in range(acquire):
        E += alpha * (1.0 - E)
        trace.append(E)
    for _ in range(extinguish):
        fear = E - I
        I += beta * fear
        trace.append(E - I)
    return {"trace": np.array(trace), "test": {"B": E - I, "A": E, "C": E}, "E": E, "I": I}


def renewal_contexts(max_contexts: int = 6, overlap: float = 0.25, **kw) -> dict:
    """Fear tested in a new context after extinction spread over n = 1 .. max_contexts different contexts.  Each
    extinction context shares ``overlap`` of its features with the new one, independently, so the new context
    retrieves a fraction g(n) = 1 - (1 - overlap)^n of the inhibition: fear there is E - g(n) I."""
    r = renewal(**kw)
    n = np.arange(1, max_contexts + 1)
    g = 1 - (1 - overlap) ** n
    return {"n": n, "g": g, "fear": r["E"] - g * r["I"], "E": r["E"], "I": r["I"]}


def helplessness(pre: str = "inescapable", n_pre: int = 64, n_test: int = 10, prior=(1.0, 1.0),
                 reps: int = 200, seed: int = 0) -> np.ndarray:
    """The triadic design as belief about control.  A learner holds a Beta belief about whether its actions control
    shock and tries to escape with probability equal to the belief's mean.  Pretreatment: ``escapable`` (trying
    always ends shock), ``inescapable`` (nothing does) or ``none``.  Test: a shuttle box where trying ends shock.
    Returns the share escaping on each test trial (over ``reps`` animals)."""
    rng = np.random.default_rng(seed)
    out = np.zeros(n_test)
    for _ in range(reps):
        a, b = prior
        if pre != "none":
            for _ in range(n_pre):
                if rng.random() < a / (a + b):
                    if pre == "escapable":
                        a += 1
                    else:
                        b += 1
        for t in range(n_test):
            if rng.random() < a / (a + b):
                a += 1
                out[t] += 1
            else:
                b += 0.2
    return out / reps


def activation(scheduled: int = 0, days: int = 90, v0: float = -0.5, reward: float = 0.6, rest: float = 0.2,
               alpha: float = 0.2, beta: float = 8.0, noise: float = 0.4, seed: int = 0) -> dict:
    """A day-by-day choice between an activity (reward ~ N(reward, noise), learned only by doing it, starting from
    the estimate v0) and rest (a known reward ``rest``), by softmax with inverse temperature beta.  For the first
    ``scheduled`` days the activity is done regardless.  Returns the estimate and the choices by day."""
    rng = np.random.default_rng(seed)
    V = v0
    est, act = np.zeros(days), np.zeros(days, bool)
    for t in range(days):
        p = 1 / (1 + np.exp(-beta * (V - rest)))
        a = t < scheduled or rng.random() < p
        if a:
            V += alpha * (rng.normal(reward, noise) - V)
        est[t], act[t] = V, a
    return {"estimate": est, "active": act}


def mood_task(n: int = 90, w=(0.5, 0.0, 0.25, 0.6), gamma: float = 0.65, noise: float = 0.25, rpe_scale: float = 1.0,
              seed: int = 0) -> dict:
    """Rutledge and colleagues' (2014) model of momentary happiness in a gambling task: each trial offers a sure
    amount or a 50/50 gamble; happiness = w0 + w1 sum gamma^(t-j) CR_j + w2 sum gamma^(t-j) EV_j + w3 sum
    gamma^(t-j) RPE_j, with CR the certain rewards taken, EV the expected value of gambles taken and RPE their outcome
    minus EV.  Simulates choices and ratings (every trial) and returns the trial data.  ``rpe_scale`` < 1 is a
    blunted response to reward prediction errors."""
    rng = np.random.default_rng(seed)
    CR = np.zeros(n)
    EV = np.zeros(n)
    RPE = np.zeros(n)
    for t in range(n):
        sure = rng.choice([-0.4, -0.2, 0.0, 0.2, 0.4])
        win, lose = rng.uniform(0.2, 1.2), rng.uniform(-1.2, -0.2)
        ev = (win + lose) / 2
        if ev > sure + rng.normal(0, 0.2):
            out = win if rng.random() < 0.5 else lose
            EV[t], RPE[t] = ev, out - ev
        else:
            CR[t] = sure
    X = _mood_design(CR, EV, RPE * rpe_scale, gamma)
    happy = np.c_[np.ones(n), X] @ np.asarray(w, float) + rng.normal(0, noise, n)
    return {"CR": CR, "EV": EV, "RPE": RPE * rpe_scale, "happy": happy, "true_w": np.asarray(w, float), "gamma": gamma}


def _mood_design(CR, EV, RPE, gamma):
    n = len(CR)
    X = np.zeros((n, 3))
    for t in range(n):
        g = gamma ** np.arange(t, -1, -1)
        X[t] = [g @ CR[:t + 1], g @ EV[:t + 1], g @ RPE[:t + 1]]
    return X


def fit_mood(d: dict, gammas=np.linspace(0.05, 0.95, 19)) -> dict:
    """Least-squares fit of the happiness model, with the forgetting factor gamma chosen on a grid."""
    best = None
    for g in gammas:
        X = np.c_[np.ones(len(d["happy"])), _mood_design(d["CR"], d["EV"], d["RPE"], g)]
        w, *_ = np.linalg.lstsq(X, d["happy"], rcond=None)
        sse = float(np.sum((d["happy"] - X @ w) ** 2))
        if best is None or sse < best[0]:
            best = (sse, g, w, X @ w)
    sse, g, w, fit = best
    r2 = 1 - sse / float(np.sum((d["happy"] - d["happy"].mean()) ** 2))
    return {"gamma": float(g), "w": w, "fit": fit, "r2": float(r2)}


def _phi(x):
    from math import erf, sqrt
    return 0.5 * (1 + erf(x / sqrt(2)))


def hollow_mask(prior_precision: float, data_precision: float = 4.0, prior_mean: float = 1.0,
                stimulus: float = -1.0) -> dict:
    """The hollow mask on a Gaussian observer.  The stereo signal x ~ N(stimulus, 1 / data_precision); the posterior
    mean is (pp * prior_mean + dp * x) / (pp + dp), and the mask looks convex when it is above 0, i.e. when
    x > -pp * prior_mean / dp.  Returns the posterior mean at the noise-free signal, the prior's weight and the
    chance of seeing the mask convex."""
    pp, dp = float(prior_precision), float(data_precision)
    w = pp / (pp + dp)
    mean = w * prior_mean + (1 - w) * stimulus
    sd = 1 / np.sqrt(dp)
    p_convex = 1 - _phi((-pp * prior_mean / dp - stimulus) / sd)
    return {"mean": float(mean), "weight": float(w), "p_convex": float(p_convex)}


def prior_tradeoff(prior_precision, data_precision: float = 4.0, p_typical: float = 0.95) -> np.ndarray:
    """Expected squared error of the posterior mean when the true depth is the prior's mean (+1) with probability
    ``p_typical`` and its mirror (-1) otherwise: (1 - w)^2 / dp + (1 - p_typical) (2 w)^2, with w the prior's
    weight.  Vectorized over ``prior_precision``."""
    pp = np.asarray(prior_precision, float)
    w = pp / (pp + data_precision)
    return (1 - w) ** 2 / data_precision + (1 - p_typical) * (2 * w) ** 2


def conditioned_hallucinations(prior_weight: float = 1.0, blocks=(0.75, 0.75, 0.5, 0.25), trials: int = 30,
                               d: float = 2.5, lr: float = 0.1, seed: int = 0, reps: int = 200) -> dict:
    """Pavlovian conditioning of hallucinations, after Powers, Mathys and Corlett (2017).  Every trial has a light;
    a tone at threshold (sensory strength d) comes with it with the block's probability, else no tone.  The learner
    holds p = P(tone | light), learned by a delta rule from what it reports hearing, and reports a tone when
    prior_weight * logit(p) + d * e - d^2 / 2 > 0, with e ~ N(d or 0, 1) the sensory evidence.  Returns the share
    of reports of a tone on tone-absent trials, per block and overall, averaged over ``reps`` learners."""
    rng = np.random.default_rng(seed)
    per_block = np.zeros(len(blocks))
    absent = np.zeros(len(blocks))
    for _ in range(reps):
        p = 0.5
        for b, q in enumerate(blocks):
            for _ in range(trials):
                tone = rng.random() < q
                e = rng.normal(d if tone else 0.0, 1.0)
                lo = prior_weight * np.log(p / (1 - p)) + d * e - d * d / 2
                heard = lo > 0
                if not tone:
                    absent[b] += 1
                    per_block[b] += heard
                p = float(np.clip(p + lr * (heard - p), 0.02, 0.98))
    rate = per_block / np.maximum(absent, 1)
    return {"by_block": rate, "overall": float(per_block.sum() / max(absent.sum(), 1)), "blocks": np.array(blocks)}


def aberrant_salience(burst_rate: float = 0.0, n_cues: int = 20, n_trials: int = 2000, alpha: float = 0.05,
                      burst: float = 1.0, threshold: float = 0.25, seed: int = 0) -> dict:
    """Kapur's aberrant salience on a Rescorla-Wagner learner.  Each trial shows one cue at random; cue 0 is followed
    by reward 1, the others by nothing.  With probability ``burst_rate`` a dopamine burst of size ``burst`` fires
    regardless, adding to the prediction error.  Returns the final value of each cue and how many irrelevant cues
    end above ``threshold``."""
    rng = np.random.default_rng(seed)
    V = np.zeros(n_cues)
    for _ in range(n_trials):
        c = int(rng.integers(n_cues))
        r = 1.0 if c == 0 else 0.0
        delta = r - V[c] + (burst if rng.random() < burst_rate else 0.0)
        V[c] += alpha * delta
    return {"V": V, "salient": int(np.sum(V[1:] > threshold)), "relevant": float(V[0])}


def redish(D: float = 0.0, reward: float = 1.0, cost: float = 0.0, n_trials: int = 300, alpha: float = 0.1) -> np.ndarray:
    """Redish's (2004) non-compensable drug signal on a one-step TD learner: delta = max(reward - cost - V + D, D)
    when D > 0 (the drug's surge cannot be predicted away), and reward - cost - V otherwise.  Returns V over
    trials: a natural reward settles at reward - cost; a drug's value rises by at least alpha * D per trial,
    whatever the cost."""
    V = 0.0
    out = np.zeros(n_trials)
    for t in range(n_trials):
        delta = reward - cost - V
        if D > 0:
            delta = max(delta + D, D)
        V += alpha * delta
        out[t] = V
    return out


def discount(amount, delay, k: float):
    """Hyperbolic discounting, V = A / (1 + k D).  Vectorized."""
    return np.asarray(amount, float) / (1 + k * np.asarray(delay, float))


ARMS = {"none": 0.0, "waitlist": -1.0, "placebo": 2.0, "active": 4.0}


def therapy_trial(arm: str = "none", n: int = 200, threshold: float = 20.0, mean: float = 14.0, sd_person: float = 5.0,
                  sd_occasion: float = 5.0, effects=None, seed: int = 0) -> dict:
    """A symptom score is a person's own mean (N(mean, sd_person)) plus occasion noise (N(0, sd_occasion)).  People are
    screened until n have a score of at least ``threshold`` (they come at their worst); each is scored again at the
    end with fresh noise, minus the arm's effect in points (``ARMS``: a waiting list's small harm, a credible
    placebo therapy's common factors, an active therapy's common and specific factors).  Returns the entry and end
    scores."""
    eff = (effects or ARMS)[arm]
    rng = np.random.default_rng(seed)
    pre, post = [], []
    while len(pre) < n:
        mu = rng.normal(mean, sd_person, 4 * n)
        x = mu + rng.normal(0, sd_occasion, 4 * n)
        keep = x >= threshold
        pre.extend(x[keep])
        post.extend(mu[keep] - eff + rng.normal(0, sd_occasion, int(keep.sum())))
    pre, post = np.array(pre[:n]), np.array(post[:n])
    return {"pre": pre, "post": post, "change": float(np.mean(post - pre))}


def trial_effect(a: str, b: str, n: int = 200, seed: int = 0) -> float:
    """Cohen's d between the end scores of arm ``b`` and arm ``a`` (positive when ``a`` ends lower)."""
    x, y = therapy_trial(a, n, seed=seed)["post"], therapy_trial(b, n, seed=seed + 1)["post"]
    sp = np.sqrt((x.var(ddof=1) + y.var(ddof=1)) / 2)
    return float((y.mean() - x.mean()) / sp)


def publication_filter(true_d: float = 0.3, k: int = 400, n_lo: int = 10, n_hi: int = 80, publish_null: float = 0.2,
                       tau: float = 0.1, seed: int = 0) -> dict:
    """k two-arm trials of a therapy with mean effect true_d (and between-trial SD tau), n per arm uniform in
    [n_lo, n_hi].  A trial is published if its one-sided p < 0.025 or, otherwise, with probability publish_null.
    Returns each trial's d, its variance, n, and whether it was published."""
    rng = np.random.default_rng(seed)
    n = rng.integers(n_lo, n_hi + 1, k)
    theta = rng.normal(true_d, tau, k)
    v = 2 / n + theta ** 2 / (4 * n)
    d = rng.normal(theta, np.sqrt(v))
    sig = d / np.sqrt(v) > 1.96
    pub = sig | (rng.random(k) < publish_null)
    return {"d": d, "v": v, "n": n, "published": pub, "significant": sig}


def random_effects(y, v) -> dict:
    """DerSimonian and Laird: inverse-variance weights, Q, tau^2 = max(0, (Q - (k - 1)) / (S1 - S2 / S1)), the
    pooled mean with weights 1 / (v + tau^2), its standard error, and I^2 = max(0, (Q - (k - 1)) / Q)."""
    y, v = np.asarray(y, float), np.asarray(v, float)
    w = 1 / v
    fixed = float(np.sum(w * y) / np.sum(w))
    Q = float(np.sum(w * (y - fixed) ** 2))
    k = len(y)
    tau2 = max(0.0, (Q - (k - 1)) / (w.sum() - (w ** 2).sum() / w.sum()))
    ws = 1 / (v + tau2)
    mu = float(np.sum(ws * y) / ws.sum())
    return {"mu": mu, "se": float(np.sqrt(1 / ws.sum())), "tau2": tau2, "I2": max(0.0, (Q - (k - 1)) / Q) if Q > 0 else 0.0,
            "fixed": fixed, "Q": Q}


def allegiance(k: int = 60, bias: float = 0.25, n: int = 40, seed: int = 0) -> dict:
    """k trials comparing two equally effective therapies A and B, each run by a team loyal to one of them (half
    each), whose loyalty adds ``bias`` to the observed advantage of their own therapy.  Returns each trial's
    observed A-minus-B effect, its variance and the team's loyalty (+1 for A, -1 for B)."""
    rng = np.random.default_rng(seed)
    loyal = np.where(np.arange(k) % 2 == 0, 1.0, -1.0)
    v = np.full(k, 2 / n)
    d = rng.normal(loyal * bias, np.sqrt(v))
    return {"d": d, "v": v, "loyal": loyal}


def reliable_change(x1, x2, sd: float, rxx: float):
    """Jacobson and Truax's RCI: (x2 - x1) / S_diff, S_diff = sqrt(2) * sd * sqrt(1 - rxx).  |RCI| > 1.96 is
    reliable change."""
    s_diff = np.sqrt(2) * sd * np.sqrt(1 - rxx)
    return (np.asarray(x2, float) - np.asarray(x1, float)) / s_diff


def jt_cutoff(m_clin: float, s_clin: float, m_well: float, s_well: float) -> float:
    """Criterion c: the point between the clinical and the well distributions, weighted by their SDs."""
    return (s_clin * m_well + s_well * m_clin) / (s_clin + s_well)


def dose_response(sessions, median: float = 8.0, at75: float = 26.0):
    """The share improved after a number of sessions, as a log-normal curve with the given median and 75th
    percentile (Howard and colleagues' 1986 summary: half improved by 8 sessions, three quarters by 26)."""
    from math import erf, log, sqrt
    sigma = (log(at75) - log(median)) / 0.6744897501960817
    s = np.atleast_1d(np.asarray(sessions, float))
    out = np.array([0.0 if x <= 0 else 0.5 * (1 + erf((log(x) - log(median)) / (sigma * sqrt(2)))) for x in s])
    return out if np.ndim(sessions) else float(out[0])
