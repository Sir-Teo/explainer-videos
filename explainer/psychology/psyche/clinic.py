"""Psyche's clinic (Part 39): what a diagnosis measures, how reliably, and how symptoms can hold each other in place.

* :func:`kappa`: Cohen's kappa for two raters, (p_o - p_e) / (1 - p_e), from a square table of counts.
* :func:`two_clinicians`: two clinicians see the same patients, each observing a latent severity with their own
  noise and calling a diagnosis above a threshold.  Returns their kappa and each one's agreement with the true
  state (above the threshold or not).  As the noise grows, kappa falls and so does validity: an unreliable
  diagnosis cannot be a valid one, since its correlation with anything is capped by the square root of its
  reliability.
* :func:`ising_network`, :func:`sweep` and :func:`episode`: a symptom network in the spirit of Cramer and
  colleagues (2016) and Borsboom (2017).  Each of n binary symptoms switches on with probability
  sigmoid(beta (b + stress + c * sum of the others' states)), updated one at a time (Glauber dynamics).  With strong
  connections c the network is bistable: as stress rises the symptoms switch on together at one level, and as
  stress falls they switch off at a lower one (hysteresis); with weak connections they rise and fall smoothly.
* :func:`comorbidity`: diagnoses generated by a general factor plus three correlated domains (internalizing,
  externalizing, thought), returning the correlation matrix among the binary diagnoses and the share of variance
  in the first principal component: comorbidity everywhere, a positive manifold, and a "p factor".
* :func:`screen`: a screening test in natural frequencies: of N people, how many have the condition, how many
  test positive, and the chance that a positive is a true case (Part 12's base rates).
* :func:`clinician_vs_formula`: Meehl's comparison.  An outcome depends linearly on a few cues; a "clinician" uses
  the right cues with weights that wander from case to case, a fitted regression uses estimated weights, and
  Dawes's improper model uses equal weights on standardized cues.  Returns each one's correlation with the
  outcome on new cases.

Part 40 adds fear and sadness:

* :func:`avoidance`: Mowrer's two factors on a Rescorla-Wagner learner: fear is acquired by pairing and kept by
  avoidance, which prevents the exposures that would extinguish it; exposure with response prevention removes it.
* :func:`renewal`: Bouton's context-bound extinction: inhibition learned in context B is expressed only in B, so
  fear returns in the old context A and in a new context C.
* :func:`renewal_contexts`: extinction practised in several contexts.  If inhibition is bound to a context's
  features and any new context shares a fraction of features with each one, the inhibition a new context retrieves
  grows with the number of extinction contexts, and the fear that returns there shrinks.
* :func:`helplessness`: the triadic design as a belief about control, with passivity as the default.
* :func:`activation`: the trap behind behavioural activation.  A learner chooses each day between an activity
  whose rewards it must sample to learn and a rest with a small, known reward; starting from a low estimate after a
  loss, it rarely acts and so never learns that acting pays.  Scheduling the activity for a fortnight breaks the
  trap.
* :func:`mood_task` and :func:`fit_mood`: Rutledge and colleagues' model of momentary happiness as a decaying sum of
  certain rewards, expected values and reward prediction errors, simulated and fitted.

Part 41 adds inference and learning set wrongly:

* :func:`hollow_mask`: Part 14's Gaussian observer seeing the inside of a mask.  A prior that faces bulge outward
  (depth +1) meets a noisy stereo signal that says hollow (-1); the percept is convex when the posterior mean is
  above 0.  Returns the posterior mean and the chance of seeing the mask convex, in closed form, for a given prior
  precision: the illusion needs a prior stronger than the eyes.
* :func:`prior_tradeoff`: what a strong prior buys and costs.  The expected squared error of the posterior mean
  when the world matches the prior (with probability ``p_typical``) or is its mirror image; strong priors win in a
  typical, noisy world and lose when it is atypical (the "too real" world of Pellicano and Burr, 2012).
* :func:`conditioned_hallucinations`: the design of Powers, Mathys and Corlett (2017) on a learner.  A light comes
  with a tone at threshold, less and less often; the learner hears a tone when its prior that light means tone,
  weighted by ``prior_weight``, plus weak sensory evidence, favours one.  Returns how often it reports a tone on
  trials with none.
* :func:`aberrant_salience`: Kapur's (2003) account on a Rescorla-Wagner learner: dopamine bursts that fire at random
  add prediction errors to whatever cue is present, and irrelevant cues acquire value ("salience").
* :func:`redish`: Redish's (2004) model of addiction.  A drug adds a dopamine surge D that cannot be learned away
  (the prediction error is never below D), so the value of the drug-taking state rises without bound while a
  natural reward's value settles at the reward, and a cost added to the drug does not stop the rise.
* :func:`discount`: hyperbolic delay discounting, V = A / (1 + kD), and the delay at which a larger, later reward
  stops being preferred to a smaller, sooner one.

Part 42 adds the evidence for therapy:

* :func:`therapy_trial`: people whose symptom scores wander around their own mean enrol when a score crosses a
  threshold, at their worst, and are scored again later; arms add nothing, a waiting list's small harm, the
  common factors of any credible therapy, or common and specific factors.  Regression to the mean and natural
  recovery make every arm improve.
* :func:`trial_effect`: the standardized difference between two arms' outcomes, so the effect depends on the control.
* :func:`publication_filter`: many trials of one true effect; the published ones are those that reached
  significance, plus a share of the rest.
* :func:`random_effects`: DerSimonian and Laird's random-effects meta-analysis: the pooled effect, its standard
  error, tau squared and I squared.
* :func:`allegiance`: comparisons of two equally good therapies, each run by a team loyal to one of them.
* :func:`reliable_change` and :func:`jt_cutoff`: Jacobson and Truax's reliable change index and the cut-off between
  the clinical and the healthy distributions.
* :func:`dose_response`: the share improved after a number of sessions, as a log-normal curve.
"""

